def replace_exact(doc, old, new):
    found = [p for p in doc.paragraphs if p.text == old]
    if len(found) != 1:
        raise RuntimeError(f"Expected one paragraph for {old!r}, found {len(found)}")
    p = found[0]
    p.text = new
    for run in p.runs:
        run.font.name = "맑은 고딕"
        run.font.size = Pt(10)


def set_cell_text(cell, value, size=8):
    cell.text = value
    for paragraph in cell.paragraphs:
        for run in paragraph.runs:
            run.font.name = "맑은 고딕"
            run.font.size = Pt(size)


